/** Width in px of `text` at pixel size `s` (glyph 5 + gap 1). */
export const textWidth = (text, s) => [...text].length * 6 * s - s;

/**
 * Pixel text as one <path> (cheaper than thousands of rects).
 * align: "start" | "middle" | "end" relative to x.
 */
export function pixelText(text, { x, y, s = 4, fill, align = "start", extra = "" }) {
  const w = textWidth(text, s);
  const x0 = align === "middle" ? x - w / 2 : align === "end" ? x - w : x;
  let d = "";
  [...text.toUpperCase()].forEach((ch, i) => {
    const g = G[ch] ?? G[" "];
    g.forEach((row, ry) => {
      let rx = 0;
      while (rx < 5) {
        if (row[rx] !== "#") { rx++; continue; }
        let run = 1;
        while (rx + run < 5 && row[rx + run] === "#") run++;
        d += `M${x0 + (i * 6 + rx) * s} ${y + ry * s}h${run * s}v${s}h${-run * s}z`;
        rx += run;
      }
    });
  });
  return `<path d="${d}" fill="${fill}" ${extra}/>`;
}

/** Text with the stepped drop shadow used on the portfolio title. */
export function pixelTitle(text, opts) {
  const { s = 4, shadow1, shadow2 } = opts;
  return (
    pixelText(text, { ...opts, y: opts.y + s * 2, fill: shadow2 }) +
    pixelText(text, { ...opts, y: opts.y + s, fill: shadow1 }) +
    pixelText(text, opts)
  );
}
